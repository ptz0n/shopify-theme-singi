#!/usr/bin/env node
/**
 * Generates docs/reference/*.md from the source of truth: LiquidDoc headers,
 * {% schema %} tags, settings_schema.json, JSON templates, locales and assets.
 *
 *   npm run docs         write the files
 *   npm run docs:check   fail if they are out of date (used in CI)
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const outDir = 'docs/reference';
const check = process.argv.includes('--check');

const read = (path) => readFileSync(join(root, path), 'utf8');
const names = (dir, ext) => readdirSync(join(root, dir)).filter((f) => f.endsWith(ext)).sort();
const HEADER = '<!-- Generated by `npm run docs`. Do not edit by hand. -->\n\n';

const schemaOf = (text) => {
  const match = text.match(/{%-?\s*schema\s*-?%}([\s\S]*?){%-?\s*endschema\s*-?%}/);
  return match ? JSON.parse(match[1]) : null;
};

const dedent = (text) => {
  const lines = text.replace(/^\n+|\s+$/g, '').split('\n');
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length), Infinity);
  return lines.map((l) => l.slice(Number.isFinite(indent) ? indent : 0)).join('\n');
};

const docOf = (text) => {
  const doc = text.match(/{%-?\s*doc\s*-?%}([\s\S]*?){%-?\s*enddoc\s*-?%}/)?.[1];
  const comment = text.match(/^\s*{%-?\s*comment\s*-?%}([\s\S]*?){%-?\s*endcomment\s*-?%}/)?.[1];
  const body = dedent(doc ?? comment ?? '');
  const description = [];
  const params = [];
  const examples = [];
  let mode = 'description';
  for (const line of body.split('\n')) {
    const param = line.match(/^@param\s+\{([^}]+)\}\s+(\[?[\w-]+\]?)(?:\s+-\s+(.*))?$/);
    if (param) {
      mode = 'param';
      params.push({ type: param[1], name: param[2].replace(/[[\]]/g, ''), optional: param[2].startsWith('['), text: param[3] ?? '' });
    } else if (/^@example/.test(line)) {
      mode = 'example';
      examples.push([]);
    } else if (mode === 'param' && params.length && line.trim()) {
      params.at(-1).text += ` ${line.trim()}`;
    } else if (mode === 'example') {
      examples.at(-1).push(line);
    } else if (mode === 'description') {
      description.push(line);
    }
  }
  return { description: description.join('\n').trim(), params, examples: examples.map((e) => e.join('\n').trim()).filter(Boolean) };
};

const settingsTable = (settings = []) => {
  const rows = settings.filter((s) => s.id).map((s) => `| \`${s.id}\` | ${s.type} | ${s.label ?? ''} | ${s.default === undefined ? '' : `\`${JSON.stringify(s.default)}\``} |`);
  return rows.length ? `| Setting | Type | Label | Default |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n` : '_No settings._\n';
};

const files = new Map();

/* snippets */
{
  let out = `${HEADER}# Snippets\n\nRendered with \`{% render 'name', param: value %}\`. Parameters come from each snippet's LiquidDoc header.\n\n`;
  for (const file of names('snippets', '.liquid')) {
    const name = file.replace('.liquid', '');
    const doc = docOf(read(`snippets/${file}`));
    out += `## ${name}\n\nFile: \`snippets/${file}\`\n\n${doc.description || '_No description._'}\n\n`;
    if (doc.params.length) {
      out += '| Param | Type | Required | Description |\n| --- | --- | --- | --- |\n';
      for (const p of doc.params) out += `| \`${p.name}\` | \`${p.type}\` | ${p.optional ? 'no' : 'yes'} | ${p.text.replace(/\|/g, '\\|')} |\n`;
      out += '\n';
    }
    for (const example of doc.examples) out += `\`\`\`liquid\n${example}\n\`\`\`\n\n`;
  }
  files.set('snippets.md', out);
}

/* blocks */
{
  let out = `${HEADER}# Theme blocks\n\nFiles in \`blocks/\`. Blocks whose name starts with \`_\` are private: they only appear in sections that list them in their schema.\n\n`;
  for (const file of names('blocks', '.liquid')) {
    const name = file.replace('.liquid', '');
    const text = read(`blocks/${file}`);
    const doc = docOf(text);
    const schema = schemaOf(text) ?? {};
    out += `## ${name}\n\nFile: \`blocks/${file}\` · Editor name: **${schema.name ?? name}** · ${name.startsWith('_') ? 'private' : 'public'}${schema.presets ? ' · has preset' : ''}\n\n${doc.description || '_No description._'}\n\n`;
    if (schema.blocks?.length) out += `Accepts child blocks: ${schema.blocks.map((b) => `\`${b.type}\``).join(', ')}\n\n`;
    out += `${settingsTable(schema.settings)}\n`;
  }
  files.set('blocks.md', out);
}

/* sections */
{
  let out = `${HEADER}# Sections\n\nFiles in \`sections/\`. Sections are thin: markup for the page region plus a slot for blocks.\n\n`;
  for (const file of names('sections', '.liquid')) {
    const name = file.replace('.liquid', '');
    const text = read(`sections/${file}`);
    const doc = docOf(text);
    const schema = schemaOf(text) ?? {};
    out += `## ${name}\n\nFile: \`sections/${file}\` · Editor name: **${schema.name ?? name}** · ${schema.presets ? 'addable in the editor' : 'template-bound'}\n\n${doc.description || '_No description._'}\n\n`;
    if (schema.blocks?.length) out += `Accepts blocks: ${schema.blocks.map((b) => `\`${b.type}\``).join(', ')}\n\n`;
    out += `${settingsTable(schema.settings)}\n`;
  }
  out += '## Section groups\n\n';
  for (const file of names('sections', '.json')) {
    const group = JSON.parse(read(`sections/${file}`));
    out += `- \`sections/${file}\`: ${group.name} (${Object.values(group.sections).map((s) => `\`${s.type}\``).join(', ')})\n`;
  }
  files.set('sections.md', out + '\n');
}

/* theme settings */
{
  let out = `${HEADER}# Theme settings\n\nDefined in \`config/settings_schema.json\`, read in Liquid as \`settings.<id>\`.\n\n`;
  for (const group of JSON.parse(read('config/settings_schema.json'))) {
    if (group.name === 'theme_info') continue;
    out += `## ${group.name}\n\n${settingsTable(group.settings)}\n`;
  }
  files.set('settings.md', out);
}

/* templates */
{
  let out = `${HEADER}# Templates\n\nJSON templates compose sections. JSON templates are eligible for Shopify's streamed responses; \`.liquid\` templates are not.\n\n| Template | Sections (in order) | Blocks in main section |\n| --- | --- | --- |\n`;
  for (const file of names('templates', '.json')) {
    const template = JSON.parse(read(`templates/${file}`));
    const sections = template.order.map((id) => `\`${template.sections[id].type}\``).join(', ');
    const blocks = template.order.flatMap((id) => (template.sections[id].block_order ?? []).map((b) => `\`${template.sections[id].blocks[b].type}\``));
    out += `| \`${file}\` | ${sections} | ${blocks.join(', ')} |\n`;
  }
  for (const file of names('templates', '.liquid')) out += `| \`${file}\` | _liquid template_ | |\n`;
  files.set('templates.md', out);
}

/* locales */
{
  const count = (obj) => Object.values(obj).reduce((n, v) => n + (v && typeof v === 'object' && !Object.keys(v).every((k) => ['zero', 'one', 'two', 'few', 'many', 'other'].includes(k)) ? count(v) : 1), 0);
  let out = `${HEADER}# Locales\n\nStorefront strings live in \`locales/<code>.json\`; \`en.default.json\` is the source. Missing locales fall back to English. Translations are machine-generated and need native review.\n\n| File | Language code | Strings |\n| --- | --- | --- |\n`;
  for (const file of names('locales', '.json')) {
    out += `| \`locales/${file}\` | ${file.replace('.default', '').replace('.json', '')} | ${count(JSON.parse(read(`locales/${file}`)))} |\n`;
  }
  files.set('locales.md', out);
}

/* assets */
{
  const liquid = ['layout', 'sections', 'snippets', 'blocks', 'templates'].flatMap((d) => names(d, '.liquid').map((f) => ({ path: `${d}/${f}`, text: read(`${d}/${f}`) })));
  let out = `${HEADER}# Assets\n\nSize in bytes (before Shopify's CDN compression) and where each asset is referenced.\n\n| Asset | Bytes | Referenced by |\n| --- | --- | --- |\n`;
  for (const file of readdirSync(join(root, 'assets')).sort()) {
    const refs = liquid.filter((l) => l.text.includes(`'${file}'`)).map((l) => `\`${l.path}\``);
    out += `| \`assets/${file}\` | ${statSync(join(root, 'assets', file)).size} | ${refs.join(', ') || '_imported by other assets_'} |\n`;
  }
  files.set('assets.md', out);
}

/* index */
files.set(
  'README.md',
  `${HEADER}# Reference\n\nGenerated from the code, always current.\n\n- [Snippets](snippets.md)\n- [Theme blocks](blocks.md)\n- [Sections](sections.md)\n- [Templates](templates.md)\n- [Theme settings](settings.md)\n- [Assets](assets.md)\n- [Locales](locales.md)\n`,
);

let drift = 0;
for (const [name, content] of files) {
  const path = join(root, outDir, name);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`out of date: ${outDir}/${name}`);
      drift += 1;
    }
  } else {
    mkdirSync(join(root, outDir), { recursive: true });
    writeFileSync(path, content);
  }
}
if (check) {
  if (drift) {
    console.error('\nRun `npm run docs` and commit the result.');
    process.exit(1);
  }
  console.log('Reference docs are up to date.');
} else {
  console.log(`Wrote ${files.size} files to ${outDir}/`);
}
